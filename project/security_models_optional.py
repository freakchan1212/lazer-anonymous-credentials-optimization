#!/usr/bin/env python3
"""Reproducible model audit, explicitly NOT a full protocol security certificate."""
import argparse, csv, hashlib, json, math, re
from pathlib import Path

ROOT = Path(__file__).resolve().parent
MODELS = {'core_sieving_ADPS16': (.292, .265, 0.), 'sieving_with_16_4_offset': (.292, .265, 16.4)}


def rhf(beta):
    return (beta / (2 * math.pi * math.e) * (math.pi * beta) ** (1 / beta)) ** (1 / (2 * (beta - 1)))


def bkz(delta):
    for beta in range(40, 20001):
        if rhf(beta) <= delta:
            return beta
    raise ValueError('RHF outside model range')


def costs(beta):
    return {k: {'classical_log2_core_svp': a * beta + c, 'quantum_log2_core_svp': b * beta + c} for k, (a, b, c) in MODELS.items()}


def lwe_primal_gsa(n, q, lo, hi):
    """Fresh single-attack GSA scan, equal-width short secret/error, m=infinity."""
    sigma = math.sqrt(((hi - lo + 1) ** 2 - 1) / 12)
    tau = sigma
    for beta in range(40, 10001):
        ld = math.log(rhf(beta))
        optimum = math.sqrt(((n + 1) * math.log(q) - math.log(tau)) / ld)
        candidates = {max(n + 2, beta + 1, math.floor(optimum)), max(n + 2, beta + 1, math.ceil(optimum))}
        lhs = math.log(sigma) + .5 * math.log(beta)
        for dimension in sorted(candidates):
            rhs = ld * (2 * beta - dimension - 1) + (math.log(tau) + math.log(q) * (dimension - n - 1)) / dimension
            if lhs <= rhs:
                return {
                    'status': 'FRESH_SINGLE_ATTACK_GSA_MODEL_SCAN', 'attack': 'primal_uSVP',
                    'n': n, 'q': q, 'sigma_secret': sigma, 'sigma_error': sigma,
                    'samples': 'unrestricted', 'embedding_dimension': dimension,
                    'bkz_blocksize': beta, 'log_success_margin': rhs - lhs,
                    'costs': costs(beta), 'ADPS16_core_costs': {'classical': .292 * beta, 'quantum': .265 * beta},
                    'excluded_attacks': ['dual', 'hybrid', 'algebraic', 'module-specific', 'auxiliary-hint-specific'],
                    'full_lattice_estimator_run': False,
                }
    raise ValueError('uSVP search limit exceeded')


def sis(n, m, q, log_bound):
    sub = max(n, min(m, round(2 * n * math.log2(q) / log_bound)))
    log_delta = (log_bound - n * math.log2(q) / sub) / sub
    if log_delta <= 0:
        raise ValueError('Inapplicable SIS model')
    delta = 2 ** log_delta
    beta = bkz(delta)
    return {
        'n': n, 'm': m, 'q': q, 'bound_log2': log_bound, 'subdimension': sub,
        'root_hermite_factor': delta, 'bkz_blocksize': beta, 'costs': costs(beta),
        'status': 'HEURISTIC_GENERIC_LATTICE_MODEL',
        'exclusions': ['structured/auxiliary-hint attacks', 'protocol reduction losses', 'full attack coverage'],
    }


def collect(header=None, variant=None, k=None):
    from security_parameters import inputs, compact_rows
    h, active_vid, selected_k, p1, p2, provenance = inputs(header, variant, k)
    is_v5 = active_vid in ['V5','C3','DC3']
    header = h.path
    parts = h.raw.split('// auto-generated by lnp-tbox.sage.')[1:]
    proofs = []
    for name, actual, text in zip(['P1','P2'], [p1,p2], parts):
        q, deg = actual['q'], actual['d']
        sn, sm = actual['kmsis'], actual['m1'] + actual['m2']
        ln, lm, lo, hi = actual['kmlwe'], actual['mlwe_embedding_rank'], -actual['nu'], actual['nu']
        msis_obj = sis(sn*deg, sm*deg, q, actual['msis_bound_log2'])
        if name == 'P2' and is_v5:
            by_k = {}
            for row in compact_rows(h):
                v = h.proof(row['param_symbol']); kk = row['disclosed_attributes_k']
                by_k[f"k_{kk}_m1_{v['m1']}"] = sis(v['kmsis']*deg, (v['m1']+v['m2'])*deg, q, v['msis_bound_log2'])
            msis_obj['full_m1_48_reference'] = by_k['k_0_m1_48']
            msis_obj['all_k_0_to_8_models'] = by_k
        fresh = lwe_primal_gsa(ln*deg, q, lo, hi)
        # Upstream multi-attack RHF is an attributed declaration, never an input to fresh scan.
        reported = float(re.search(r'// MLWE root hermite factor: ([\d.]+)',text)[1])
        item = dict(name=name,proof_ring_degree=deg,proof_modulus=q,
            knowledge_error_exponent_upper_bound=-127.0,
            knowledge_error_status='CONDITIONAL_GENERATOR_EXPRESSION_NOT_EMPIRICAL',
            MSIS=msis_obj,MLWE=dict(n=ln*deg,m_header_embedding=lm*deg,q=q,
            secret_and_error_uniform=[lo,hi],header_root_hermite_factor=reported,
            header_rhf_evidence='REPORTED_UPSTREAM_MULTI_ATTACK_ESTIMATOR_DECLARATION_NOT_RERUN',
            bkz_blocksize_from_header=bkz(reported),costs=costs(bkz(reported)),
            status='ATTRIBUTED_UPSTREAM_RHF_ONLY_FRESH_SCAN_SEPARATE',fresh_primal_usvp_gsa=fresh),
            repetition_rate_theoretical=math.prod(actual['rejection_factors']),
            lambda_repetitions=actual['lambda_repetitions'],actual_parameters=actual)
        proofs.append(item)
    meta = json.loads((ROOT / 'vendor/ESTIMATOR_PROVENANCE.json').read_text()) if (ROOT / 'vendor/ESTIMATOR_PROVENANCE.json').exists() else {}
    return {
        'schema_version': 3, 'active_variant': active_vid, 'parameter_source': provenance,
        'status': 'MODEL_AUDIT_COMPLETE_FULL_PROTOCOL_NOT_CERTIFIED', 'target_security_bits': 128,
        'model_definitions': {
            'rhf': '(beta/(2*pi*e)*(pi*beta)^(1/beta))^(1/(2*(beta-1)))',
            'models': MODELS,
            'interpretation': 'log2 heuristic Core-SVP oracle cost; not measured CPU time, not a proven lower bound or whole-protocol security bits',
        },
        'proofs': proofs,
        'Falcon_NTRU_512_preimage_generic_model': sis(p2['norm_dimensions'][1]*p2['d']//2, p2['norm_dimensions'][1]*p2['d'], p2['p'], .5 * math.log2(p2['norm_bounds_sq'][1])),
        'protocol_security': {
            'unforgeability': {'numeric_bound': None, 'status': 'REDUCTION_AND_HINT_ASSUMPTION_NOT_INSTANTIATED', 'definition': 'credential unforgeability under the BLNS family; Falcon signature security alone does not establish it'},
            'anonymity_unlinkability': {'numeric_bound': None, 'status': 'CONDITIONAL_ON_LNP_ZK_AND_PROTOCOL_MODEL', 'definition': 'hide undisclosed blocks and credential witness; excludes identifying disclosed data, network metadata and unmodelled collusion'},
            'zero_knowledge_error': {'numeric_bound': None, 'status': 'UPSTREAM_CONDITIONAL_MLWE_SIMULATION; FULL_ADVANTAGE_BOUND_NOT_INSTANTIATED'},
            'session_binding': {'status': 'NOT_ADDED_IN_ORIGINAL_BASELINE', 'assumptions': 'no session/context digest added; original Fiat-Shamir transcript retained'},
            'replay': 'original credential demo has no authentication-session challenge; behavior retained',
            'holder_binding': 'not added; possession of full credential material is sufficient; credential sharing resistance not claimed',
            'revocation_traceability': 'not implemented or claimed',
        },
        'estimator': meta, 'native_attack_scan': 'SIS_GENERIC_LATTICE_AND_LWE_PRIMAL_GSA_ONLY',
        'full_attack_scan': 'NOT_RUN_UNLESS_08_security_sage.sh_IS_EXECUTED',
        'source_hashes': {str(p): hashlib.sha256(p.read_bytes()).hexdigest() for p in [header, ROOT / 'lazer/scripts/codegen.sage', ROOT / 'lazer/scripts/lnp-tbox-codegen.sage']},
        'references': [
            'https://github.com/Chair-for-Security-Engineering/lattice-anonymous-credentials/blob/main/scripts/estimate_SIS_LWE.py',
            'https://cjeudy.github.io/assets/pub/AGJLRS24_Pratical_Post-Quantum_Signatures_for_Privacy.pdf',
            'https://eprint.iacr.org/2023/560',
            'https://eprint.iacr.org/2026/291',
        ],
    }


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--output', type=Path, default=ROOT / 'results/security_static')
    ap.add_argument('--header', type=Path); ap.add_argument('--variant'); ap.add_argument('--disclosed-k',type=int)
    a = ap.parse_args()
    a.output.mkdir(parents=True, exist_ok=True)
    d = collect(a.header,a.variant,a.disclosed_k)
    (a.output / 'security.json').write_text(json.dumps(d, indent=2))
    rows = []
    for p in d['proofs']:
        for kind in ['MSIS', 'MLWE']:
            x = p[kind]
            for model, c in x['costs'].items():
                rows.append({
                    'component': p['name'] + '_' + kind, 'model': model,
                    'beta': x.get('bkz_blocksize', x.get('bkz_blocksize_from_header')),
                    'classical_cost_log2': c['classical_log2_core_svp'],
                    'quantum_cost_log2': c['quantum_log2_core_svp'], 'evidence': x['status'],
                })
        fresh = p['MLWE']['fresh_primal_usvp_gsa']
        rows.append({
            'component': p['name'] + '_MLWE_fresh_primal_GSA', 'model': 'ADPS16_core_no_BKZ_overhead',
            'beta': fresh['bkz_blocksize'], 'classical_cost_log2': fresh['ADPS16_core_costs']['classical'],
            'quantum_cost_log2': fresh['ADPS16_core_costs']['quantum'], 'evidence': fresh['status'],
        })
    for model, c in d['Falcon_NTRU_512_preimage_generic_model']['costs'].items():
        rows.append({
            'component': 'Falcon_NTRU_generic_preimage', 'model': model,
            'beta': d['Falcon_NTRU_512_preimage_generic_model']['bkz_blocksize'],
            'classical_cost_log2': c['classical_log2_core_svp'],
            'quantum_cost_log2': c['quantum_log2_core_svp'],
            'evidence': 'HEURISTIC_GENERIC_LATTICE_MODEL_NOT_BLNS_UNFORGEABILITY',
        })
    with (a.output / 'security_costs.csv').open('w', newline='') as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0]))
        w.writeheader()
        w.writerows(rows)
    print('MODEL_AUDIT_COMPLETE; full protocol security and fresh full attack scan are not certified')


if __name__ == '__main__':
    main()
