#!/usr/bin/env python3
"""Actual generated C parameters, explicit archived-header selection, scoped evidence."""
import argparse,csv,json,math,re
from pathlib import Path
from security_parameters import ROOT,inputs,compact_rows,DEFAULT_HEADER

def delta_msis(B,kmsis,d,q):return 2**(math.log2(B)**2/(4*d*kmsis*math.log2(q)))
def compute_p2_compact_table(header=None):
    from security_parameters import Header
    return compact_rows(Header(header or DEFAULT_HEADER))
def collect(header=None,variant=None,k=None):
    h,v,k,p1,p2,src=inputs(header,variant,k);compact=v in ['V5','C3','DC3']
    parts=h.raw.split('// auto-generated by lnp-tbox.sage.')[1:];rows=[]
    for name,p,t in zip(['P1','P2'],[p1,p2],parts):
        reported=lambda pattern: re.search(pattern,t)[1]
        rows.append(dict(component=name,proof_degree=p['d'],proof_modulus=p['q'],m1_secret_polys=p['m1'],binary_polys=p['nbin'],
            knowledge_error_log2_upstream=float(reported(r'knowledge error <= 2\^\((-?[\d.]+)\)')),
            MSIS_original=f"MSIS({p['kmsis']},{p['m1']+p['m2']},2^({p['msis_bound_log2']:.6f}))",
            MLWE_original=f"MLWE({p['kmlwe']},{p['mlwe_embedding_rank']},[-{p['nu']},{p['nu']}])",
            MSIS_rhf_original=float(reported(r'// MSIS root hermite factor: ([\d.]+)')),
            MSIS_rhf_recomputed=round(p['MSIS_rhf'],7),
            MLWE_rhf_original=float(reported(r'// MLWE root hermite factor: ([\d.]+)')),
            theoretical_repetition_rate_original=math.prod(p['rejection_factors'])))
    return dict(version='E4-FIX123-1',active_variant=v,parameter_source=src,status='ACTUAL_HEADER_CONFIGURATION_RECORDED',
        relation_degree=p1['relation_degree'],relation_modulus=p1['p'],P1_relation_shape=[8,p1['m1']],P2_relation_shape=[8,p2['m1']],
        credential_relation=dict(P1_relation_shape=[8,p1['m1']],P2_relation_shape=[8,p2['m1']],P2_compact_subspace_table=compact_rows(h) if compact else None),
        proofs=rows,parameter_header_sha256=src['header_sha256'],upstream_generator_target_bits=128,
        target_interpretation='generator target and attributed assumptions, not a protocol security certification',
        compact_family_enabled=compact,security_parameters_changed=compact and k>0,protocol_modified=compact and k>0,session_extension=False,
        extra_verification_checks=v!='B0',bugfixes_applied=v!='B0',optimizations_applied=v not in ['B0','B1'],
        actual_parameters=[p1,p2],classical_quantum_new_estimates='see attack_costs.csv; declared generic attacks only',
        numeric_protocol_security_certified=False,
        attribution_note='*_original fields are upstream declarations; compact MSIS_original reconstructed from selected actual header. Fresh arithmetic separately labeled.')
def main():
    ap=argparse.ArgumentParser();ap.add_argument('--output',type=Path,default=ROOT/'results/security_static');ap.add_argument('--header',type=Path);ap.add_argument('--variant');ap.add_argument('--disclosed-k',type=int);a=ap.parse_args()
    d=collect(a.header,a.variant,a.disclosed_k);a.output.mkdir(parents=True,exist_ok=True)
    (a.output/'security.json').write_text(json.dumps(d,indent=2)+'\n')
    with (a.output/'upstream_security_configuration.csv').open('w',newline='') as f:
        w=csv.DictWriter(f,fieldnames=list(d['proofs'][0]));w.writeheader();w.writerows(d['proofs'])
    from security_metrics import write
    write(a.output,d)
    print('SECURITY_AND_METRICS_RECORDED',d['active_variant'],d['parameter_header_sha256'])
if __name__=='__main__':main()
